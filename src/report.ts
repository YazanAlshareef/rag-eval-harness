// npm run replay -> scores everything in cache/ offline (no key, no app, no network)
// and writes results.json, chart.png and REPORT.md. Every number comes from cache/ + data/.
import fs from "node:fs";
import path from "node:path";
import { chartPng } from "./chart.ts";
import { citationOk, hit, metrics, rubric, type Question, type Rec } from "./score.ts";

type Cached = { meta: { provider: string; config: { name: string; topK: number; chatModel?: string }; ranAt: string; appCommit: string }; records: Rec[] };
type Spot = { provider: string; config: string; id: string; verdict: "correct" | "incorrect"; note: string; by: string };

const qs: Question[] = fs.readFileSync("data/questions.jsonl", "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
const cfgs = JSON.parse(fs.readFileSync("configs.json", "utf8"));
const spots: Spot[] = fs.existsSync("data/spot_check.json") ? JSON.parse(fs.readFileSync("data/spot_check.json", "utf8")) : [];

const pct = (r: { rate: number | null; ci: [number, number] | null; num: number; den: number } | null) =>
  !r || r.rate === null ? "n/a" : `${(r.rate * 100).toFixed(0)}% (${r.num}/${r.den}; 95% CI ${(r.ci![0] * 100).toFixed(0)}-${(r.ci![1] * 100).toFixed(0)}%)`;

const results: Record<string, unknown> = {};
const lines: string[] = [];
const out = (s = "") => lines.push(s);
out("# RAG evaluation report");
out();
out("Generated by `npm run replay` from the saved outputs in `cache/`. Every number below is computed from those files; nothing is typed in by hand except the caveats.");
out();

for (const provider of ["fixture", "gemini"] as const) {
  const dir = path.join("cache", provider);
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort() : [];
  const label = cfgs[provider].label as string;
  if (!files.length) {
    results[provider] = { status: "not run with live key" };
    out(`## ${provider === "gemini" ? "Live Gemini" : provider}`);
    out();
    out("**Not run with live key.** No saved Gemini outputs exist, so there are no live numbers. To produce them see README \"Run it\".");
    out();
    continue;
  }
  const loaded = files.map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")) as Cached);
  const pricing = cfgs[provider].pricing?.models;
  const rows = loaded.map((c) => ({ c, m: metrics(c.records, qs, c.meta.config.chatModel, pricing) }));
  results[provider] = {
    label,
    pricing: cfgs[provider].pricing ?? null,
    configs: Object.fromEntries(rows.map(({ c, m }) => [c.meta.config.name, { ...c.meta, metrics: m }])),
  };

  out(`## ${provider === "fixture" ? "FIXTURE run (offline stand-in, not Gemini)" : "Live Gemini run"}`);
  out();
  out(`> ${label}`);
  out();
  out(`Configs: ${rows.map(({ c }) => `**${c.meta.config.name}** (top-k ${c.meta.config.topK}${c.meta.config.chatModel ? ", " + c.meta.config.chatModel : ""})`).join(" vs ")}. Run at ${loaded[0].meta.ranAt}, app commit \`${loaded[0].meta.appCommit.slice(0, 7)}\`.`);
  out();
  const head = ["Metric", ...rows.map(({ c }) => c.meta.config.name)];
  const table = (name: string, f: (m: (typeof rows)[number]["m"]) => string) => out(`| ${name} | ${rows.map(({ m }) => f(m)).join(" | ")} |`);
  out(`| ${head.join(" | ")} |`);
  out(`|${head.map(() => "---").join("|")}|`);
  table("Retrieval hit rate (expected section in top-k, answerable only)", (m) => pct(m.retrievalHit));
  table("Answer correct, rubric (numbers in key fact appear; only questions whose key fact has a number)", (m) => pct(m.rubricPass));
  table("Answer correct, LLM judge", (m) => (m.judgeCorrect ? pct(m.judgeCorrect) : provider === "fixture" ? "not run (no model in fixture mode)" : "not run"));
  table("Citation accuracy (among answered answerable)", (m) => pct(m.citationAccuracy));
  table("Refusal accuracy (unanswerable should be refused)", (m) => pct(m.refusalAccuracy));
  table("False refusals (answerable but refused)", (m) => pct(m.falseRefusal));
  table("Latency median / p95", (m) => (m.latencyMs ? `${m.latencyMs.median} / ${m.latencyMs.p95} ms` : "n/a"));
  table("Estimated cost for 40 questions", (m) => (m.estCostUsd === null ? "n/a (fixture: no paid calls)" : `$${m.estCostUsd.toFixed(4)}`));
  out();
  if (provider === "fixture") out("Fixture latency is the speed of local hashing code, not of any model. Do not compare it with live latency.");
  else out(`Cost is an estimate: tokens are counted as characters / 4 (the app does not return real token counts) and priced from ${cfgs.gemini.pricing.source}. Embedding cost for the 40 queries is left out (tiny).`);
  out();

  // Conclusions are generated from the numbers, then hedged.
  if (rows.length === 2) {
    const [a, b] = rows;
    out("### What the numbers say");
    out();
    // Paired comparison: same questions in both configs, so count the questions where they differ.
    // Overlapping confidence intervals are the wrong test here because the two samples are not independent.
    const ra = new Map(a.c.records.map((r) => [r.id, r])), rb = new Map(b.c.records.map((r) => [r.id, r]));
    const paired: [string, (r: Rec, q: Question) => boolean | null][] = [
      ["retrieval hit (answerable questions)", (r, q) => (q.expect === "answer" ? hit(r, q) : null)],
      ["citation accuracy (answered answerable questions)", (r, q) => (q.expect === "answer" && !r.refused ? citationOk(r, q) : null)],
      ["refusal accuracy (unanswerable questions)", (r, q) => (q.expect === "refuse" ? r.refused : null)],
    ];
    for (const [nm, f] of paired) {
      let onlyA = 0, onlyB = 0, both = 0, n = 0;
      for (const q of qs) {
        const x = f(ra.get(q.id)!, q), y = f(rb.get(q.id)!, q);
        if (x === null || y === null) continue; // not comparable in one of the configs
        n++;
        if (x && y) both++;
        else if (x) onlyA++;
        else if (y) onlyB++;
      }
      const d = onlyA + onlyB;
      // two-sided exact sign test on the questions where the configs differ
      let p = 1;
      if (d > 0) {
        const m = Math.min(onlyA, onlyB);
        let tail = 0;
        for (let k = 0; k <= m; k++) { let c = 1; for (let i = 0; i < k; i++) c = (c * (d - i)) / (i + 1); tail += c * 0.5 ** d; }
        p = Math.min(1, 2 * tail);
      }
      out(`- ${nm}, ${n} comparable questions: both right ${both}, only ${a.c.meta.config.name} right ${onlyA}, only ${b.c.meta.config.name} right ${onlyB}. ${d === 0 ? "No question differs." : `Sign test p = ${p.toFixed(3)} on ${d} differing questions${p < 0.05 ? ": a real difference is plausible, but it rests on a small sample." : ": this sample cannot separate them."}`}`);
    }
    out();
    if (provider === "fixture") out("This fixture comparison is about retrieval only. The fixture refuses when the best passage scores below a threshold, and the best passage is the same at top-k 2 and 4, so refusal is identical by construction. Top-k only changes which passages can be cited. It says nothing about how Gemini answers.");
    else out("Pairs are the same question run under both configs. With 40 questions, a gap of a few questions is not evidence.");
    out();
  }

  // Per-question misses, so every number can be traced.
  out("### Misses (traceable per question)");
  out();
  for (const { c } of rows) {
    const byId = new Map(c.records.map((r) => [r.id, r]));
    const miss = qs.filter((q) => {
      const r = byId.get(q.id)!;
      return q.expect === "answer" ? r.refused || rubric(r, q) === false : !r.refused;
    });
    out(`- **${c.meta.config.name}**: ${miss.length ? miss.map((q) => q.id).join(", ") : "none"}  (refused an answerable question, failed the rubric, or answered an unanswerable one)`);
  }
  out();

  // Spot check
  const mine = spots.filter((s) => s.provider === provider);
  if (mine.length) {
    out("### Hand spot-check");
    out();
    out(`${mine.length} items were read one by one and compared with the automatic rubric. **The reader was an AI coding assistant, not Yazan** (${[...new Set(mine.map((m) => m.by))].join("; ")}). Verdicts live in \`data/spot_check.json\`.`);
    out();
    out("**To do by hand:** Yazan should redo these 10 checks by hand on the saved answers (and again on a live run) before anyone relies on this table. Until then it is an assistant's reading, not a human check.");
    out();
    out("| Config | Question | Hand verdict | Rubric | Note |");
    out("|---|---|---|---|---|");
    for (const s of mine) {
      const c = loaded.find((x) => x.meta.config.name === s.config);
      const r = c?.records.find((x) => x.id === s.id);
      const q = qs.find((x) => x.id === s.id);
      if (!r || !q) continue;
      const rb = rubric(r, q);
      out(`| ${s.config} | ${s.id} | ${s.verdict} | ${rb === null ? "n/a" : rb ? "pass" : "fail"} | ${s.note} |`);
    }
    out();
  }
}

out("![chart](chart.png)");
out();
out("## Caveats");
out();
out("- **Small sample.** 40 questions, 30 answerable and 10 that should be refused. One question moves a rate by 2 to 3 points. Confidence intervals are wide; read differences smaller than about 15 points as noise.");
out("- **Fixture numbers are not Gemini numbers.** The fixture is a word-matching stand-in. It shows the harness works, not how the real app performs.");
out("- **The rubric is crude.** It checks numbers only, so key facts without a number (for example \"yes, VLTP can be combined\") get no rubric score. A wrong answer that happens to contain the right number passes.");
out("- **The LLM judge is another model's opinion** and has not been checked against humans yet (the spot-check above covers fixture output only and was done by the assistant, not by a human). It exists only in live runs.");
out("- **Citation accuracy** counts an answer as accurate if one cited passage is the expected section; it does not check that the cited text supports the sentence.");
out("- **Questions were written by an AI coding assistant** (per the app's README), not by a domain expert, and the same 40 were used to tune the fixture threshold, so fixture scores are optimistic.");
out("- **Cost** is an estimate from character counts, not billed usage.");
out("- **Single run per config.** Live models are not deterministic; no repeats were done.");
out();

fs.writeFileSync("results.json", JSON.stringify({ generatedBy: "npm run replay", providers: results }, null, 2) + "\n");

// Chart: every provider that has data, one PNG each (fixture clearly labelled).
for (const provider of ["fixture", "gemini"] as const) {
  const p = results[provider] as { configs?: Record<string, { metrics: ReturnType<typeof metrics> }> };
  if (!p.configs) continue;
  const names = Object.keys(p.configs);
  const get = (f: (m: ReturnType<typeof metrics>) => { rate: number | null } | null) => names.map((n) => f(p.configs![n].metrics)?.rate ?? null);
  await chartPng(
    provider === "fixture" ? "chart.png" : "chart-gemini.png",
    "RAG eval: " + names.join(" vs "),
    provider === "fixture" ? "FIXTURE data (offline stand-in model, not Gemini). n=40 questions." : "Live Gemini. n=40 questions.",
    ["Retrieval hit", "Rubric correct", "Judge correct", "Citation acc.", "Refusal acc."],
    names.map((n, i) => ({
      name: n,
      values: [get((m) => m.retrievalHit), get((m) => m.rubricPass), get((m) => m.judgeCorrect), get((m) => m.citationAccuracy), get((m) => m.refusalAccuracy)].map((v) => v[i]),
    })),
  );
}
fs.writeFileSync("REPORT.md", lines.join("\n") + "\n");
console.log("wrote results.json, chart.png, REPORT.md");
